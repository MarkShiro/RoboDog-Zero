// =====================================================================
//  steppers.h — генератор шагов на восемь моторов и настройка TMC2209.
//
//  Шаги формируются в прерывании таймера с частотой STEP_ISR_HZ.
//  У каждого мотора свой 16-битный накопитель: на каждом тике к нему
//  прибавляется приращение, пропорциональное скорости, и переполнение
//  накопителя означает «пора сделать шаг». Это тот же приём, что в
//  цифровых синтезаторах частоты: дробные скорости получаются без
//  деления и без накопления ошибки.
//
//  Все восемь выводов STEP лежат на PORTA, поэтому импульсы для всех
//  моторов ставятся одной записью в порт — прерывание получается очень
//  коротким и не мешает остальному коду.
// =====================================================================
#pragma once
#include "config.h"

namespace Steppers {

void begin();                       // настроить выводы и таймер
bool setupDrivers(bool (*service)()); // remain disabled; abort if service fails
bool checkDriver(uint8_t index);
bool timingFault();
void renewLease(uint16_t controlRemainingMs=250);
void setBounds(bool on);
uint8_t driversOnline();            // сколько драйверов ответило

void enable(bool on);               // общий вывод EN
bool enabled();

// Целевая скорость мотора в шагах в секунду. Знак задаёт направление.
// Реальная скорость подтягивается к целевой с ускорением ACCEL_SPS2.
void setSpeed(uint8_t m, int16_t sps);
void setAllSpeeds(int16_t sps);
void stopAll();                     // мгновенно обнулить скорости

void tick();                        // разгон и торможение, звать в loop()

int32_t position(uint8_t m);        // текущая позиция в шагах
void zero(uint8_t m);               // объявить текущую точку нулём
int16_t speed(uint8_t m);

// Ток удержания задаётся долей от рабочего. Меньше ток — больше автономность,
// но сустав хуже держит нагрузку.
void setHoldMultiplier(float k);

}  // namespace Steppers
