// =====================================================================
//  leds.h — индикация состояния лентой WS2811 на 12 В.
//
//  Осторожно с моментом обновления: библиотека на время передачи
//  запрещает прерывания, а у нас в прерывании живёт генератор шагов.
//  Поэтому лента обновляется редко и только тогда, когда картинка
//  действительно изменилась.
// =====================================================================
#pragma once
#include "config.h"

enum LedMode : uint8_t {
  LED_BOOT = 0,    // синяя бегущая волна
  LED_OK,          // ровный зелёный
  LED_WARN,        // жёлтый
  LED_SHUTDOWN,    // жёлтый мигающий
  LED_OFFREADY,    // зелёный только на первом сегменте
  LED_ESTOP,       // красный
  LED_FAULT        // красный мигающий
};

class Leds {
public:
  void begin();
  void set(LedMode m);
  void update(bool motorsMoving);

private:
  LedMode  _mode = LED_BOOT;
  uint8_t  _phase = 0;
  uint32_t _next = 0;
  bool     _dirty = true;
};
